export const demoProfileSlugs = ["cafe", "quick-service", "full-service"] as const;
export type DemoProfileSlug = (typeof demoProfileSlugs)[number];

export const defaultDemoProfileSlug: DemoProfileSlug = "cafe";

export const demoProfileOptions: Array<{ slug: DemoProfileSlug; label: string }> = [
  { slug: "cafe", label: "Cafe / Bakery" },
  { slug: "quick-service", label: "Quick-Service / Takeout" },
  { slug: "full-service", label: "Full-Service Restaurant" },
];

export function isDemoProfileSlug(value: string | undefined): value is DemoProfileSlug {
  return demoProfileSlugs.includes((value ?? "") as DemoProfileSlug);
}

export function buildDemoPath(slug: DemoProfileSlug, segment = "") {
  return segment ? `/demo/${slug}/${segment}` : `/demo/${slug}`;
}

function priceStatus(changePercent: number) {
  if (changePercent >= 3) return "Increased";
  if (changePercent <= -3) return "Decreased";
  return "Stable";
}

function severity(changePercent: number): Severity {
  const absoluteChange = Math.abs(changePercent);
  if (absoluteChange >= 10) return "High";
  if (absoluteChange >= 5) return "Medium";
  return "Low";
}

function createSupplierSpend(suppliers: DemoProfileData["suppliers"]): SupplierSpend[] {
  return suppliers.map((supplier) => ({
    supplierId: supplier.id,
    supplier: supplier.name,
    spend: supplier.totalSpendMonth,
    invoices: supplier.invoicesMonth,
    change: supplier.averagePriceChange,
  }));
}

function createPriceChanges(trackedItems: TrackedItem[]): PriceChange[] {
  return trackedItems.map((item) => ({
    id: item.id,
    item: item.name,
    supplier: item.preferredSupplier,
    category: item.category,
    previousPrice: item.previousPrice,
    currentPrice: item.lastPrice,
    changePercent: item.changePercent,
    dateDetected: item.lastPurchasedDate,
    severity: item.severity,
    status: item.status,
    suggestedAction:
      item.changePercent >= 10
        ? "Review the menu, verify the next invoice, and compare one alternate supplier."
        : item.changePercent >= 5
          ? "Watch the next order and check whether the increase is repeating."
          : item.changePercent <= -3
            ? "Capture the savings and keep tracking this item."
            : "No urgent action. Keep monitoring this item.",
  }));
}

function buildInvoiceSummary(invoices: InvoiceSummary[]): InvoiceSummary[] {
  return invoices;
}

function hydrateCopy(copy: DemoProfileCopy, customization: DemoProfileData["customization"], period: string): DemoProfileCopy {
  const templateValues: Record<string, string> = {
    restaurantName: customization.restaurantName,
    city: customization.city,
    restaurantType: customization.restaurantType,
    primarySupplier: customization.primarySupplier,
    ownerPainPoint: customization.ownerPainPoint,
    period,
  };

  const hydrate = (value: string) =>
    value.replace(
      /\{\{(restaurantName|city|restaurantType|primarySupplier|ownerPainPoint|period)\}\}/g,
      (_, key: keyof typeof templateValues) => templateValues[key] ?? "",
    );

  return {
    dashboard: {
      title: hydrate(copy.dashboard.title),
      eyebrow: hydrate(copy.dashboard.eyebrow),
      description: hydrate(copy.dashboard.description),
    },
    dailyReconciliation: {
      title: hydrate(copy.dailyReconciliation.title),
      eyebrow: hydrate(copy.dailyReconciliation.eyebrow),
      description: hydrate(copy.dailyReconciliation.description),
    },
    invoices: {
      title: hydrate(copy.invoices.title),
      eyebrow: hydrate(copy.invoices.eyebrow),
      description: hydrate(copy.invoices.description),
    },
    priceTracker: {
      title: hydrate(copy.priceTracker.title),
      eyebrow: hydrate(copy.priceTracker.eyebrow),
      description: hydrate(copy.priceTracker.description),
    },
    reports: {
      title: hydrate(copy.reports.title),
      eyebrow: hydrate(copy.reports.eyebrow),
      description: hydrate(copy.reports.description),
    },
    settings: {
      title: hydrate(copy.settings.title),
      eyebrow: hydrate(copy.settings.eyebrow),
      description: hydrate(copy.settings.description),
    },
  };
}

type DemoProfileSeed = Omit<DemoProfileData, "supplierSpend" | "priceChanges" | "extractedInvoice" | "copy"> & {
  copy: DemoProfileCopy;
};

function makeProfile(seed: DemoProfileSeed): DemoProfileData {
  const hydratedCopy = hydrateCopy(seed.copy, seed.customization, seed.period);
  const supplierSpend = createSupplierSpend(seed.suppliers);
  const priceChanges = createPriceChanges(seed.trackedItems);
  const extractedInvoice = {
    id: seed.invoices[0].id,
    supplier: seed.invoices[0].supplier,
    invoiceDate: seed.invoices[0].invoiceDate,
    invoiceNumber: seed.invoices[0].invoiceNumber,
    totalAmount: seed.invoices[0].totalAmount,
    status: seed.invoices[0].status,
    items: seed.invoices[0].lineItems,
  };

  return {
    ...seed,
    copy: hydratedCopy,
    supplierSpend,
    priceChanges,
    extractedInvoice,
  };
}

